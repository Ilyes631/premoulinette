/** Adds the student source line that printed each differing line (as compare/evaluate.py does). */
function withSources(diff: TextDiff, file: string, lines: Record<number, number>): TextDiff {
  return {
    ...diff,
    lines: diff.lines.map((line) => {
      const src = line.actual_lineno !== null ? lines[line.actual_lineno] : undefined
      return src ? { ...line, source: makeLocation(file, src) } : line
    }),
  }
}

const out = (text: string, file: string, line: number): TranscriptEvent => ({
  kind: 'output',
  text,
  location: makeLocation(file, line),
})
const typed = (text: string, file: string, line: number): TranscriptEvent => ({
  kind: 'input',
  text,
  location: makeLocation(file, line),
})

